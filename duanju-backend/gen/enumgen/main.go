// enumgen 从迁移 SQL（migrations/000002_enum_types.up.sql）解析 CREATE TYPE 定义，
// 生成三件套：Go 常量集（internal/pkg/enums）、TS 类型联合（packages/api-client/src/types/enums.ts）、
// 入参校验器（Go validator oneof 标签）。
//
// 用法（在 duanju-backend/ 目录）：
//
//	go run ./gen/enumgen
package main

import (
	"fmt"
	"go/format"
	"os"
	"path/filepath"
	"regexp"
	"sort"
	"strings"
)

var (
	reTypeName = regexp.MustCompile(`(?i)^\s*CREATE\s+TYPE\s+(\w+)\s+AS\s+ENUM\s*\(`)
	reEnumVal  = regexp.MustCompile(`'([A-Z0-9_]+)'`)
)

type enumDef struct {
	Name string
	Vals []string
}

func main() {
	// 定位仓库根：从 duanju-backend/ 向上
	root, err := repoRoot()
	if err != nil {
		fatal(err)
	}
	backend := filepath.Join(root, "duanju-backend")
	src := filepath.Join(backend, "migrations", "000002_enum_types.up.sql")

	data, err := os.ReadFile(src)
	if err != nil {
		fatal(err)
	}
	defs, err := parse(string(data))
	if err != nil {
		fatal(err)
	}
	if err := writeGo(defs, filepath.Join(backend, "internal", "pkg", "enums", "enums_gen.go")); err != nil {
		fatal(err)
	}
	if err := writeTS(defs, filepath.Join(root, "packages", "api-client", "src", "types", "enums.ts")); err != nil {
		fatal(err)
	}
	fmt.Printf("enumgen: %d 个枚举已生成（Go + TS）\n", len(defs))
}

func fatal(err error) {
	fmt.Fprintln(os.Stderr, "enumgen:", err)
	os.Exit(1)
}

func repoRoot() (string, error) {
	dir, err := os.Getwd()
	if err != nil {
		return "", err
	}
	for range 5 {
		if _, err := os.Stat(filepath.Join(dir, "duanju-backend")); err == nil {
			return dir, nil
		}
		dir = filepath.Dir(dir)
	}
	return "", fmt.Errorf("未找到仓库根（缺少 duanju-backend 目录）")
}

func parse(src string) ([]enumDef, error) {
	var defs []enumDef
	var cur *enumDef
	for _, line := range strings.Split(src, "\n") {
		if m := reTypeName.FindStringSubmatch(line); m != nil {
			cur = &enumDef{Name: m[1]}
			defs = append(defs, *cur)
			cur = &defs[len(defs)-1]
			// 注意：不 continue，单行定义时值可能在同一行。
		}
		if cur == nil {
			continue
		}
		for _, vm := range reEnumVal.FindAllStringSubmatch(line, -1) {
			cur.Vals = append(cur.Vals, vm[1])
		}
		// 多行定义时，遇到独立的 ");" 结束当前枚举；单行定义（值与 ");" 同行）时
		// 需在值解析后结束，此处通过“该行含值且以 ); 结尾”判定。
		if cur != nil && strings.HasSuffix(strings.TrimSpace(line), ");") && len(cur.Vals) > 0 {
			cur = nil
		}
	}
	if len(defs) == 0 {
		return nil, fmt.Errorf("未解析到任何 CREATE TYPE")
	}
	// 去重（迁移中不会重复，保险）
	seen := map[string]bool{}
	out := defs[:0]
	for _, d := range defs {
		if !seen[d.Name] {
			seen[d.Name] = true
			out = append(out, d)
		}
	}
	sort.Slice(out, func(i, j int) bool { return out[i].Name < out[j].Name })
	return out, nil
}

func goConstName(enumName, val string) string {
	return strings.ToUpper(enumName[:1]) + enumName[1:] + "_" + val
}

func writeGo(defs []enumDef, path string) error {
	var b strings.Builder
	b.WriteString("// Code generated by gen/enumgen. DO NOT EDIT.\n")
	b.WriteString("// 枚举唯一真源 = migrations/000002_enum_types.up.sql（对齐 02 - 数据库设计.md A 章）。\n")
	b.WriteString("// 业务代码一律引用本文件常量，禁止手写枚举值。\n\n")
	b.WriteString("package enums\n\n")
	b.WriteString("import \"strings\"\n\n")
	b.WriteString("// 枚举 → 合法值集合（供 validator oneof 校验器引用）\n")
	b.WriteString("var Allowed = map[string]string{\n")
	for _, d := range defs {
		b.WriteString(fmt.Sprintf("\t%q: %q,\n", d.Name, strings.Join(d.Vals, "|")))
	}
	b.WriteString("}\n\n")
	for _, d := range defs {
		b.WriteString(fmt.Sprintf("// %s 枚举类型\ntype %s string\n\n", d.Name, d.Name))
		b.WriteString(fmt.Sprintf("// %s 枚举常量\nconst (\n", d.Name))
		for _, v := range d.Vals {
			b.WriteString(fmt.Sprintf("\t%s %s = %q\n", goConstName(d.Name, v), d.Name, v))
		}
		b.WriteString(")\n\n")
	}
	b.WriteString("// IsValid 校验值是否属于枚举合法集合。\n")
	b.WriteString("func IsValid(enumName, val string) bool {\n")
	b.WriteString("\tallowed, ok := Allowed[enumName]\n")
	b.WriteString("\tif !ok {\n")
	b.WriteString("\t\treturn false\n")
	b.WriteString("\t}\n")
	b.WriteString("\tfor _, v := range strings.Split(allowed, \"|\") {\n")
	b.WriteString("\t\tif v == val {\n")
	b.WriteString("\t\t\treturn true\n")
	b.WriteString("\t\t}\n")
	b.WriteString("\t}\n")
	b.WriteString("\treturn false\n")
	b.WriteString("}\n\n")
	b.WriteString("// OneOfTag 返回 validator 的 oneof 校验 tag（如 oneof=PENDING QUEUED）。\n")
	b.WriteString("func OneOfTag(enumName string) string {\n")
	b.WriteString("\tallowed, ok := Allowed[enumName]\n")
	b.WriteString("\tif !ok {\n")
	b.WriteString("\t\treturn \"\"\n")
	b.WriteString("\t}\n")
	b.WriteString("\treturn \"oneof=\" + strings.ReplaceAll(allowed, \"|\", \" \")\n")
	b.WriteString("}\n")

	code, err := format.Source([]byte(b.String()))
	if err != nil {
		return fmt.Errorf("Go 格式化失败: %w", err)
	}
	if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
		return err
	}
	return os.WriteFile(path, code, 0o644)
}

func writeTS(defs []enumDef, path string) error {
	var b strings.Builder
	b.WriteString("// Code generated by gen/enumgen. DO NOT EDIT.\n")
	b.WriteString("// 枚举唯一真源 = duanju-backend/migrations/000002_enum_types.up.sql（对齐 02 - 数据库设计.md A 章）。\n\n")
	for _, d := range defs {
		b.WriteString(fmt.Sprintf("export type %s =\n", d.Name))
		for i, v := range d.Vals {
			sep := "  | "
			if i == len(d.Vals)-1 {
				sep = "  | "
			}
			b.WriteString(fmt.Sprintf("%s'%s'\n", sep, v))
		}
		b.WriteString("\n")
	}
	b.WriteString("// 枚举名 → 合法值集合\n")
	b.WriteString("export const EnumAllowed: Record<string, readonly string[]> = {\n")
	for _, d := range defs {
		b.WriteString(fmt.Sprintf("  %s: [%s],\n", d.Name, joinQuoted(d.Vals)))
	}
	b.WriteString("};\n\n")
	b.WriteString("export function isEnumValue<T extends string>(name: string, val: string): val is T {\n")
	b.WriteString("  return (EnumAllowed[name] ?? []).includes(val);\n")
	b.WriteString("}\n")
	if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
		return err
	}
	return os.WriteFile(path, []byte(b.String()), 0o644)
}

func joinQuoted(vals []string) string {
	quoted := make([]string, len(vals))
	for i, v := range vals {
		quoted[i] = "'" + v + "'"
	}
	return strings.Join(quoted, ", ")
}
